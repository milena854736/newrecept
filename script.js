const CATS = ['ЗАВТРАКИ', 'ОБЕД (Первые блюда)', 'ОБЕД (Вторые блюда)', 'ОБЕД (Десерты)', 'ПОЛДНИК', 'УЖИН', 'МОИ РЕЦЕПТЫ'];

// ==================== ХРАНИЛИЩЕ ====================
function loadUserRecipes() {
  try { return JSON.parse(localStorage.getItem('userRecipes') || '[]'); }
  catch (e) { return []; }
}
function saveUserRecipes(list) {
  localStorage.setItem('userRecipes', JSON.stringify(list));
}

// ==================== СОСТОЯНИЕ ====================
let currentCat = 'ВСЕ';
let openId = null;

// ==================== РЕНДЕР ====================
function allRecipes() {
  return CATS.flatMap(cat => RECIPES[cat].map(r => ({ ...r, cat })));
}

function matchesFilters(r) {
  const name = document.getElementById('searchName').value.trim().toLowerCase();
  const ing = document.getElementById('searchIngredient').value.trim().toLowerCase();
  if (name && !r.name.toLowerCase().includes(name)) return false;
  if (ing && !r.ingredients.some(p => p[0].toLowerCase().includes(ing))) return false;
  return true;
}

function render() {
  const list = document.getElementById('recipeList');
  const emptyMsg = document.getElementById('emptyMessage');
  const title = document.getElementById('sectionTitle');
  list.innerHTML = '';

  let items;
  if (currentCat === 'ВСЕ') {
    items = allRecipes();
    title.textContent = 'Все блюда (' + items.length + ')';
  } else if (currentCat === 'МОИ РЕЦЕПТЫ') {
    items = loadUserRecipes().map(r => ({ ...r, cat: 'МОИ РЕЦЕПТЫ', user: true }));
    title.textContent = 'Мои рецепты (' + items.length + ')';
  } else {
    items = RECIPES[currentCat].map(r => ({ ...r, cat: currentCat }));
    title.textContent = currentCat + ' (' + items.length + ')';
  }

  items = items.filter(matchesFilters);

  if (!items.length) { emptyMsg.classList.remove('hidden'); return; }
  emptyMsg.classList.add('hidden');

  items.forEach(r => {
    const card = document.createElement('article');
    card.className = 'recipe-card' + (openId === r.id ? ' open' : '');
    card.dataset.id = r.id;

    const head = document.createElement('div');
    head.className = 'recipe-head';
    head.innerHTML =
      '<div><div class="recipe-title">🍽 ' + esc(r.name) + '</div>' +
      '<div class="recipe-meta">[' + esc(r.id) + '] ' + esc(r.cat) + ' · ⏱ ' + esc(r.time) +
      ' · 👥 ' + r.servings + ' · 🔥 ~' + r.calories + ' ккал</div></div>' +
      '<button class="btn-dl" type="button">⬇ txt</button>';
    card.appendChild(head);

    const body = document.createElement('div');
    body.className = 'recipe-body';
    body.innerHTML =
      '<div class="body-h">📝 Ингредиенты:</div><ul>' +
      r.ingredients.map(p => '<li>' + esc(p[0]) + ': ' + esc(p[1]) + '</li>').join('') +
      '</ul><div class="body-h">👨‍🍳 Приготовление:</div><ol>' +
      r.steps.map(s => '<li>' + esc(s) + '</li>').join('') + '</ol>';
    card.appendChild(body);

    card.addEventListener('click', function (e) {
      if (e.target.closest('.btn-dl')) return;
      openId = (openId === r.id) ? null : r.id;
      render();
    });
    head.querySelector('.btn-dl').addEventListener('click', function (e) {
      e.stopPropagation();
      downloadRecipe(r);
    });

    list.appendChild(card);
  });
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ==================== СКАЧИВАНИЕ РЕЦЕПТА ====================
function downloadRecipe(r) {
  let text = 'РЕЦЕПТ: ' + r.name + '\n';
  text += 'Время: ' + r.time + '\n';
  text += 'Порции: ' + r.servings + '\n';
  text += 'Калории: ' + r.calories + ' ккал\n\n';
  text += 'ИНГРЕДИЕНТЫ:\n';
  r.ingredients.forEach(p => { text += '- ' + p[0] + ': ' + p[1] + '\n'; });
  text += '\nПРИГОТОВЛЕНИЕ:\n';
  r.steps.forEach((s, i) => { text += (i + 1) + '. ' + s + '\n'; });

  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = r.name.replace(/[\\/:*?"<>|]/g, '_') + '.txt';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(a.href);
  showToast('Рецепт сохранён в файл: ' + a.download);
}

// ==================== СЛУЧАЙНЫЙ РЕЦЕПТ ====================
function pickRandom() {
  const pool = allRecipes().concat(loadUserRecipes().map(r => ({ ...r, cat: 'МОИ РЕЦЕПТЫ' })));
  if (!pool.length) { showToast('База пуста'); return; }
  const r = pool[Math.floor(Math.random() * pool.length)];
  currentCat = r.cat;
  document.getElementById('searchName').value = '';
  document.getElementById('searchIngredient').value = '';
  openId = r.id;
  document.querySelectorAll('.cat-btn').forEach(b =>
    b.classList.toggle('active', b.dataset.cat === currentCat));
  render();
  const card = document.querySelector('.recipe-card[data-id="' + CSS.escape(r.id) + '"]');
  if (card) card.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

// ==================== ДОБАВЛЕНИЕ РЕЦЕПТА ====================
function addUserRecipe() {
  const name = document.getElementById('inpName').value.trim();
  const time = document.getElementById('inpTime').value.trim() || 'неизвестно';
  const cal = parseInt(document.getElementById('inpCal').value, 10) || 0;
  const ingRaw = document.getElementById('inpIng').value.trim();
  const stepsRaw = document.getElementById('inpSteps').value.trim();

  if (!name || !ingRaw || !stepsRaw) { showToast('Заполните название, ингредиенты и шаги'); return; }

  const ing = ingRaw.split(',').map(s => s.trim()).filter(Boolean).map(s => [s, 'по вкусу']);
  const steps = stepsRaw.split('.').map(s => s.trim()).filter(Boolean);
  const list = loadUserRecipes();
  list.push({
    id: 'user.' + (list.length + 1) + '.' + Date.now(),
    name: name, time: time, servings: 1, calories: cal,
    ingredients: ing, steps: steps
  });
  saveUserRecipes(list);

  document.getElementById('inpName').value = '';
  document.getElementById('inpTime').value = '';
  document.getElementById('inpCal').value = '';
  document.getElementById('inpIng').value = '';
  document.getElementById('inpSteps').value = '';

  currentCat = 'МОИ РЕЦЕПТЫ';
  openId = list[list.length - 1].id;
  document.querySelectorAll('.cat-btn').forEach(b =>
    b.classList.toggle('active', b.dataset.cat === currentCat));
  render();
  showToast('Рецепт добавлен в раздел «Мои рецепты»!');
}

// ==================== УВЕДОМЛЕНИЯ ====================
let toastTimer = null;
function showToast(msg) {
  const t = document.getElementById('toast');
  t.textContent = msg;
  t.classList.remove('hidden');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.classList.add('hidden'), 2800);
}

